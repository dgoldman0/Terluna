def drift_winds(zw, height_km, hull_c, dark_lat):
    """What the winds at a town's height do to a drifting town, from the zonal-winds diagnostic: its solar day, how
    long it keeps one time of day, where drifting towns gather, and the power a streamlined hull needs to hold a
    time of day against the wind."""
    axes = zw['axes']
    i = axes['height_km'].index(height_km)
    lat = np.asarray(axes['lat_deg'], float)
    hours = np.asarray(axes['hour_angle_deg'], float)
    bands = []
    for b in zw['bands']:
        if b['height_km'][0] <= height_km < b['height_km'][1]:
            bands.append(dict(height_km=b['height_km'], abs_lat_deg=b['abs_lat_deg'], eastward_mean_m_s=b['u_mean_m_s'],
                              sun_speed_m_s=b['sun_speed_m_s'],
                              solar_day_days_p10_p50_p90=[b['day_p10_days'], b['day_p50_days'], b['day_p90_days']],
                              share_within_1_m_s_of_the_sun=b['hold_1'], best_hour_deg=b['hold_1_peak_hour_deg'],
                              share_within_1_m_s_at_best_hour=b['hold_1_peak_share'], sun_turned_back=b['reversed']))
    t = zw['trajectories']
    j = t['heights_km'].index(height_km)
    fy = t['sequence']['first_year']
    release = t['release_lat_deg']
    routes = {str(l): dict(solar_day_days_p10_p50_p90=[fy['first_pass_p10_days'][j][k], fy['first_pass_p50_days'][j][k],
                                                         fy['first_pass_p90_days'][j][k]],
                           longest_in_one_30_deg_of_hours_days=[fy['dwell_p50_days'][j][k], fy['dwell_max_days'][j][k]],
                           sun_up_share=fy['sun_up_share_p50'][j][k])
              for k, l in enumerate(release)}
    occ = np.asarray(fy['occupancy'][j], float).sum(axis=1)                     # by 10-degree latitude band
    edges = np.asarray(t['occupancy_lat_edges_deg'], float)
    area = np.asarray(t['area_share'], float) * len(t['occupancy_hour_edges_deg'][:-1])
    gather = [dict(lat_deg=[float(edges[k]), float(edges[k + 1])], share=r(float(occ[k])),
                   over_area_share=r(float(occ[k] / area[k]))) for k in range(occ.size)]
    # occupancy on this study's latitude bands, spreading each 10-degree band's share evenly over its area
    def band_share(lo, hi):
        tot = 0.0
        for k in range(occ.size):
            a, b = edges[k], edges[k + 1]
            for sgn_lo, sgn_hi in ((lo, hi), (-hi, -lo)):
                x0, x1 = max(a, sgn_lo), min(b, sgn_hi)
                if x1 > x0:
                    whole = math.sin(math.radians(b)) - math.sin(math.radians(a))
                    tot += occ[k] * (math.sin(math.radians(x1)) - math.sin(math.radians(x0))) / whole
        return tot
    occupancy = {'equatorial': band_share(0.0, 15.0), 'tropical': band_share(15.0, RAIN_BELT_DEG),
                 'middle': band_share(RAIN_BELT_DEG, dark_lat), 'high': band_share(dark_lat, 90.0)}
    # holding a time of day: the airspeed against the wind in the Sun's frame, with the spread of the 3-day means
    vs = np.asarray(zw['sun_speed_m_s'], float)[i]
    um = np.asarray(zw['sun_frame']['u_mean_m_s'], float)[i]
    vm = np.asarray(zw['sun_frame']['v_mean_m_s'], float)[i]
    gf = zw['ground_frame']
    su = (np.asarray(gf['u_p90_m_s'], float)[i] - np.asarray(gf['u_p10_m_s'], float)[i]) / 2.563
    sv = (np.asarray(gf['v_p90_m_s'], float)[i] - np.asarray(gf['v_p10_m_s'], float)[i]) / 2.563
    w = np.sqrt((um + vs[:, None]) ** 2 + vm ** 2 + su[:, None] ** 2 + sv[:, None] ** 2)
    hold = []
    for row in range(lat.size):
        ok = np.isfinite(w[row])
        if not ok.any():
            continue
        best = int(np.nanargmin(np.where(ok, w[row], np.inf)))
        hold.append(dict(lat_deg=r(float(lat[row])), sun_speed_m_s=r(float(vs[row])),
                         best_hour_deg=float(hours[best]), airspeed_m_s_best_hour=r(float(w[row, best])),
                         airspeed_m_s_hour_mean=r(float(np.nanmean(w[row]))),
                         hull_kw_per_resident_best_hour=r(hull_c * float(w[row, best]) ** 3),
                         hull_kw_per_resident_hour_mean=r(hull_c * float(np.nanmean(w[row] ** 3)))))
    return dict(source=ZONAL_WINDS, status='read from the zonal-winds diagnostic', height_km=height_km,
                bands=bands, routes_by_release_lat=routes, gathering_by_lat=gather,
                occupancy_by_band={k: r(v) for k, v in occupancy.items()}, hold_time_of_day=hold,
                rule=('Holding a time of day takes an airspeed of |u + v_sun| eastward and |v| northward against the '
                      'Sun-frame mean wind at the best hour, with the spread of the 3-day means (10th to 90th '
                      'percentile over 2.563 standard deviations) added in quadrature; the streamlined hull pays the '
                      'cube of that airspeed.'))


def zonal_or_global(winds, clim, clim_meta):
    """The winds a drifting town meets: the zonal-winds diagnostic when it exists, otherwise the stored global-mean
    eastward wind by model layer, a placeholder marked as such."""
    path = ROOT / ZONAL_WINDS
    if path.exists():
        return dict(source=ZONAL_WINDS, sha16=digest(path), status='present; not yet read by this runner')
    sigma = clim['sigma'].astype(float)
    ua = clim['ua_layer_mean'].astype(float)
    hk = np.asarray(winds['height_km'], float)
    p = np.asarray(winds['pressure_pa'], float)
    p0 = clim_meta['configuration']['pressure_pa']
    heights = np.interp(np.log(sigma * p0)[::-1], np.log(p)[::-1], hk[::-1])[::-1]
    in_profile = sigma * p0 >= p.min()
    u = float(np.interp(AERIAL_HEIGHT_KM, heights[::-1], ua[::-1]))
    sun = 2.0 * math.pi * MOON_RADIUS / (SYNODIC_MONTH_DAYS * JULIAN_DAY)
    month = SYNODIC_MONTH_DAYS * 24.0
    days = {str(lat): r(month * sun * math.cos(math.radians(lat)) / (sun * math.cos(math.radians(lat)) + u))
            for lat in (0, 30, 45, 60)}
    return dict(source='climate/gcm/products/climatology_A28_dim5_moon.npz (ua_layer_mean, global mean by layer)',
                status=f'placeholder until the zonal-winds diagnostic ({ZONAL_WINDS}) lands',
                layer_heights_km=[r(x) if ok else None for x, ok in zip(heights, in_profile)],
                layer_eastward_m_s=rr(ua), eastward_at_aerial_height_m_s=r(u),
                drifting_town_solar_day_hours_by_lat=days,
                speed_p50_at_aerial_height_m_s=r(float(np.interp(AERIAL_HEIGHT_KM, hk, winds['speed_p50_m_s']))))


