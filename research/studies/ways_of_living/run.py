# The atlas grid: land, water, sides, heights, climate and the settings' home regions.

def pixel_areas(lat_deg, ppd, ncols):
    top = np.radians(lat_deg + 0.5 / ppd)
    bottom = np.radians(lat_deg - 0.5 / ppd)
    row = (MOON_RADIUS / 1e3) ** 2 * math.radians(1.0 / ppd) * (np.sin(top) - np.sin(bottom))
    return np.repeat(row[:, None], ncols, axis=1)


def regrid(clim, name, lat, lon):
    """Bilinear interpolation of a T21 field onto the atlas grid (as geography/drainage.py does onto 16 px/deg)."""
    f = clim[name].astype(float)
    order = np.argsort(clim['lat'])
    ls, fs = clim['lat'][order].astype(float), f[order]
    lon_src = np.concatenate([clim['lon'] - 360.0, clim['lon'], clim['lon'] + 360.0]).astype(float)
    fs = np.concatenate([fs, fs, fs], axis=1)
    la = np.clip(lat, ls[0], ls[-1])
    i = np.clip(np.searchsorted(ls, la) - 1, 0, ls.size - 2)
    ty = ((la - ls[i]) / (ls[i + 1] - ls[i]))[:, None]
    j = np.clip(np.searchsorted(lon_src, lon) - 1, 0, lon_src.size - 2)
    tx = ((lon - lon_src[j]) / (lon_src[j + 1] - lon_src[j]))[None, :]
    top = fs[i][:, j] * (1 - tx) + fs[i][:, j + 1] * tx
    bottom = fs[i + 1][:, j] * (1 - tx) + fs[i + 1][:, j + 1] * tx
    return top * (1 - ty) + bottom * ty


def shift(a, dr, dc, fill):
    s = np.roll(a, dc, axis=1)
    if dr == 1:
        s = np.vstack([np.full((1, s.shape[1]), fill, s.dtype), s[:-1]])
    elif dr == -1:
        s = np.vstack([s[1:], np.full((1, s.shape[1]), fill, s.dtype)])
    return s


def neighbours(mask):
    """Cells 8-adjacent to a mask, longitude periodic, poles closed."""
    out = np.zeros_like(mask)
    for dr in (-1, 0, 1):
        for dc in (-1, 0, 1):
            if dr or dc:
                out |= shift(mask, dr, dc, False)
    return out


def lakes_by_size(drainage, ppd16=16):
    """Rain-fed lake cells at 16 px/deg labelled into lakes (8-connected, joined across the seam) with each lake's
    area; returns the lake and big-lake cell masks and the shore lengths of each class."""
    rows, cols = 180 * ppd16, 360 * ppd16
    lake = np.zeros(rows * cols, bool)
    lake[drainage['lake_cell']] = True
    lake = lake.reshape(rows, cols)
    lat16 = 90.0 - (np.arange(rows) + 0.5) / ppd16
    area_row = pixel_areas(lat16, ppd16, 1)[:, 0]
    lab, n = ndimage.label(lake, structure=np.ones((3, 3), int))
    parent = np.arange(n + 1)

    def find(x):
        while parent[x] != x:
            parent[x] = parent[parent[x]]
            x = parent[x]
        return x
    a, b = lab[:, 0], lab[:, -1]
    for p, q in sorted(set(zip(a[(a > 0) & (b > 0)].tolist(), b[(a > 0) & (b > 0)].tolist()))):
        rp, rq = find(p), find(q)
        if rp != rq:
            parent[rq] = rp
    roots = np.array([find(i) for i in range(n + 1)])
    lab = roots[lab]
    areas = np.bincount(lab.ravel(), weights=np.repeat(area_row, cols), minlength=n + 1)
    areas[0] = 0.0
    big_label = areas >= BIG_WATER_KM2
    big_label[0] = False
    big = big_label[lab]
    ns = MOON_RADIUS / 1e3 * math.radians(1.0 / ppd16)
    ew = ns * np.cos(np.radians(lat16))

    def shore_km(m):
        """Lake edges against land, with the pi/4 staircase correction for random orientation."""
        km = sum(np.count_nonzero(m & ~np.roll(lake, sh, axis=1)) for sh in (1, -1)) * ns
        km += float(((m & ~shift(lake, 1, 0, False)).sum(axis=1) * ew).sum())
        km += float(((m & ~shift(lake, -1, 0, False)).sum(axis=1) * ew).sum())
        return km * math.pi / 4.0
    stats = dict(lakes=int(np.count_nonzero(areas > 0)), big_lakes=int(big_label.sum()),
                 big_lake_area_km2=r(float(areas[big_label].sum()), 4),
                 small_lake_area_km2=r(float(areas[(areas > 0) & ~big_label].sum()), 4),
                 big_lake_shore_km=r(shore_km(big), 3), small_lake_shore_km=r(shore_km(lake & ~big), 3))
    return lake, big, stats


def to_coarse(fine, factor):
    """Share of fine cells set within each coarse cell."""
    rows, cols = fine.shape
    return fine.reshape(rows // factor, factor, cols // factor, factor).mean(axis=(1, 3))


def great_circle_km(lat1, lon1, lat2, lon2):
    p1, p2 = np.radians(lat1), np.radians(lat2)
    c = np.clip(np.sin(p1) * np.sin(p2) + np.cos(p1) * np.cos(p2) * np.cos(np.radians(lon2 - lon1)), -1.0, 1.0)
    return MOON_RADIUS / 1e3 * np.arccos(c)


def unit(lat, lon):
    la, lo = np.radians(lat), np.radians(lon)
    return np.stack([np.cos(la) * np.cos(lo), np.cos(la) * np.sin(lo), np.sin(la)], axis=-1)


def chord_km(chord):
    return 2.0 * MOON_RADIUS / 1e3 * np.arcsin(np.minimum(chord / 2.0, 1.0))


def loop_points(loop, turn_deg, n=720):
    """Points along a regional magnet loop on the surface, its centre turned about the polar axis (as the joint
    synthesis's magnets map draws them)."""
    c = np.array(loop['centre'], float)
    nrm = np.array(loop['normal'], float)
    nrm /= np.linalg.norm(nrm)
    t = math.radians(turn_deg)
    rot = np.array([[math.cos(t), -math.sin(t), 0.0], [math.sin(t), math.cos(t), 0.0], [0.0, 0.0, 1.0]])
    c, nrm = rot @ c, rot @ nrm
    a = np.cross(nrm, [0.0, 0.0, 1.0])
    a = a / np.linalg.norm(a) if np.linalg.norm(a) > 1e-9 else np.array([1.0, 0.0, 0.0])
    b = np.cross(nrm, a)
    s = np.linspace(0.0, 2.0 * math.pi, n, endpoint=False)
    p = c[None, :] + loop['radius'] * (np.cos(s)[:, None] * a + np.sin(s)[:, None] * b)
    p /= np.linalg.norm(p, axis=1, keepdims=True)
    return np.degrees(np.arcsin(p[:, 2])), np.degrees(np.arctan2(p[:, 1], p[:, 0])) % 360.0


def coast_length_km(water, lat, ppd):
    ns = MOON_RADIUS / 1e3 * math.radians(1.0 / ppd)
    lat_b = (lat[1:] + lat[:-1]) / 2.0
    e_h = np.count_nonzero(water != np.roll(water, 1, axis=1)) * ns
    e_v = float(((water[1:] != water[:-1]).sum(axis=1) * ns * np.cos(np.radians(lat_b))).sum())
    return (e_h + e_v) * math.pi / 4.0


def build_grid(atlas_grid, atlas_meta, drainage, clim, summit, magnets, magnets_map, tides, heritage, dark_lat):
    h = atlas_grid['height_m'].astype(float)
    water_label = atlas_grid['water_label']
    lat, lon = atlas_grid['lat_deg'].astype(float), atlas_grid['lon_deg'].astype(float)
    ppd = int(round(1.0 / abs(lat[0] - lat[1])))
    area = pixel_areas(lat, ppd, lon.size)
    sea_level = float(atlas_meta['sea_level_m'])
    hsl_km = (h - sea_level) / 1e3
    water = water_label > 0
    body_area = np.bincount(water_label.ravel(), weights=area.ravel())
    big_body = body_area >= BIG_WATER_KM2
    big_body[0] = False
    atlas_big = big_body[water_label] & water
    atlas_small = water & ~atlas_big
    lake16, big16, lake_stats = lakes_by_size(drainage)
    factor = lake16.shape[0] // h.shape[0]
    f_lake = np.where(water, 0.0, to_coarse(lake16, factor))
    f_big = np.where(water, 0.0, to_coarse(big16, factor))
    f_small = f_lake - f_big
    del lake16, big16
    land = np.where(water, 0.0, area)
    dry = land * (1.0 - f_lake)
    cells = drainage['channel_cell'][drainage['channel_discharge_m3s'] >= LARGE_RIVER_M3_S]
    cols16 = lon.size * factor
    river = np.zeros(h.shape, bool)
    river[(cells // cols16) // factor, (cells % cols16) // factor] = True
    river &= ~water
    LA, LO = np.meshgrid(lat, lon, indexing='ij')
    cos_t = np.cos(np.radians(LA)) * np.cos(np.radians(LO))
    earth_elev = 90.0 - np.degrees(np.arccos(np.clip(cos_t, -1.0, 1.0)))
    lon_c = np.radians(((LO + 180.0) % 360.0) - 180.0)
    az = np.arctan2(np.sin(lon_c) * np.cos(np.radians(LA)), np.sin(np.radians(LA)))
    reach = np.hypot(LIBRATION_LONGITUDE_DEG * np.sin(az), LIBRATION_LATITUDE_DEG * np.cos(az))
    side = np.where(earth_elev > reach, 0, np.where(earth_elev < -reach, 2, 1))
    metro = (great_circle_km(LA, LO, summit['lat'], summit['lon']) <= summit['radius_km']) & ~water
    big_wet = atlas_big | (f_big >= 0.5)
    small_wet = atlas_small | (f_small >= 0.5)
    shore_big = ~water & (neighbours(big_wet) | (f_big > 0.0))
    margin = ~water & (neighbours(small_wet) | (f_small > 0.0) | river)
    alat = np.abs(LA)
    cls = np.zeros(h.shape, np.int8)
    free = ~water
    for code, mask in ((1, metro), (2, shore_big), (3, margin), (4, hsl_km >= HIGHLAND_KM),
                       (5, alat < RAIN_BELT_DEG), (6, (alat < dark_lat) & (side == 0)),
                       (7, (alat < dark_lat) & (side == 1)), (8, (alat < dark_lat) & (side == 2)),
                       (9, alat >= dark_lat)):
        take = free & mask
        cls[take] = code
        free &= ~take
    pr = regrid(clim, 'pr_mm_day', lat, lon)
    ev = regrid(clim, 'evap_mm_day', lat, lon)
    runoff = np.maximum(pr - ev, 0.0)
    # sea coasts' monthly tide: the neighbouring atlas body's median range
    lut = np.full(int(water_label.max()) + 1, np.nan)
    for k, v in tides['seas'].items():
        if int(k) < lut.size:
            lut[int(k)] = v['monthly_range_median_m']['area_median']
    tide = np.full(h.shape, np.nan)
    for dr in (-1, 0, 1):
        for dc in (-1, 0, 1):
            s = shift(water_label, dr, dc, 0)
            tide = np.where(~water & (s > 0), np.fmax(tide, lut[s]), tide)
    # distances from land to the nearest standing water and to the nearest sea or great water (great circle, km)
    xyz = unit(LA, LO)
    landmask = ~water
    dist = {}
    for name, target in (('any_water', water | (f_lake >= 0.5)), ('sea', atlas_big)):
        chord, _ = cKDTree(xyz[target]).query(xyz[landmask])
        km = np.zeros(h.shape)
        km[landmask] = chord_km(chord)
        dist[name] = km
    # the regional magnets' 0.5 mT corridors at the turn that keeps most heritage and science sites clear
    corridor = {}
    for design, info in magnets_map['designs'].items():
        loops = next(x for x in magnets['regional'] if x['name'] == design)['loops']
        points = np.concatenate([unit(*loop_points(loop, info['fewest_sites_and_targets'])) for loop in loops])
        chord, _ = cKDTree(points).query(xyz[landmask])
        inside = np.zeros(h.shape, bool)
        inside[landmask] = chord_km(chord) <= info['corridor_km']
        corridor[design] = inside
    sites = []
    for s in heritage['sites']:
        i = int(np.clip(np.round((lat[0] - s['lat']) * ppd), 0, lat.size - 1))
        j = int(np.round((s['lon'] % 360.0 - lon[0]) * ppd)) % lon.size
        sites.append(dict(name=s['name'], status=s['status'], cls=int(cls[i, j]), side=SIDES[int(side[i, j])]))
    gcm_row_of_lat = np.abs(clim['lat'].astype(float)[None, :] - lat[:, None]).argmin(axis=1)
    return dict(lat=lat, lon=lon, LA=LA, LO=LO, area=area, land=land, dry=dry, water=water, f_lake=f_lake,
                gcm_row=np.repeat(gcm_row_of_lat[:, None], lon.size, axis=1).astype(np.int16),
                hsl_km=hsl_km, side=side, earth_elev=earth_elev, cls=cls, pr=pr, ev=ev, runoff=runoff, tide=tide,
                dist=dist, corridor=corridor, sites=sites, lake_stats=lake_stats, sea_level_m=sea_level, ppd=ppd,
                coast_km=coast_length_km(water, lat, ppd))


def bands_of(g, dark_lat):
    """Water bands: the two halves of the rain belt, the middle latitudes and the latitudes without a dark night."""
    alat = np.abs(g['LA'])
    return {'equatorial': alat < 15.0, 'tropical': (alat >= 15.0) & (alat < RAIN_BELT_DEG),
            'middle': (alat >= RAIN_BELT_DEG) & (alat < dark_lat), 'high': alat >= dark_lat}


def km3_year(mm_day, area_km2):
    """mm a day over km2 to km3 a year (1 mm over 1 km2 is 1e-6 km3)."""
    return float((mm_day * area_km2).sum() * 1e-6 * JULIAN_YEAR_DAYS)


def weighted_pct(values, weights, qs):
    order = np.argsort(values, kind='stable')
    v, w = values[order], weights[order]
    cw = np.cumsum(w) / w.sum()
    return [float(v[min(np.searchsorted(cw, q), v.size - 1)]) for q in qs]


def warmth(tas, g, mask, dry, mean_height_km):
    """The GCM's land air through the lunar day at the region's latitudes, moved to the region's mean ground height
    two ways: with the design run's free-air profile (global mean) and with the register's 1 C per km."""
    lat_rows, field, free_h, free_t, land_mean_h = tas
    rows = g['gcm_row'][mask]
    w = dry[mask]
    lo, hi, mean = (np.nanmin(field, axis=1)[rows], np.nanmax(field, axis=1)[rows],
                    np.nanmean(field, axis=1)[rows])
    ok = np.isfinite(lo) & np.isfinite(hi)
    if not ok.any():
        return None
    base_h = land_mean_h[rows]
    free = np.interp(mean_height_km, free_h, free_t) - np.interp(base_h, free_h, free_t)
    register = -REGISTER_LAPSE_K_PER_KM * (mean_height_km - base_h)

    def avg(x):
        return float((x[ok] * w[ok]).sum() / w[ok].sum())
    return dict(coolest_hour_mean_c=r(avg(lo + free) - 273.15), warmest_hour_mean_c=r(avg(hi + free) - 273.15),
                lunar_day_mean_c=r(avg(mean + free) - 273.15), height_shift_free_air_k=r(avg(free)),
                lunar_day_mean_c_register_lapse=r(avg(mean + register) - 273.15),
                height_shift_register_k=r(avg(register)), gcm_rows_land_height_km=r(avg(base_h)))


def night_by_sky(up, far_lat, places, marks, curve):
    """The night's own light by the sky the land lies under. The Earthlit and limb skies read main's places (bound);
    the far side's night is the solved sky's twilight at the far-side land's median latitude."""
    rows = []
    for key, sky, place in (('high', 'nearside, the Earth high', 'southern Mare Nubium'),
                            ('low', 'nearside, the Earth low', 'Oceanus Procellarum by Russell'),
                            ('rising_and_setting', 'limb, the Earth rising and setting', 'eastern Smythii headland')):
        p = places[place]
        rows.append(dict(sky=sky, share=up[key], read_from=place, darkest_lux=p['night']['natural_darkest_lux'],
                         midnight_lux=p['night']['natural_midnight_lux'],
                         hours_below_0_1_lux=p['night']['hours_below_0_1_lux_natural'],
                         flashes_per_km2_year=p['lightning']['central']))
    if far_lat is not None:
        t = twilight(far_lat, marks, curve)
        rows.append(dict(sky='far side, no Earth', share=up['never'], read_from=f'solved sky at {r(far_lat)} deg',
                         darkest_lux=t['darkest_sky_lux'], hours_below_0_1_lux=t['below_0_1_lux_sky_hours'],
                         beyond_practical_dusk_hours=t['beyond_practical_dusk_hours']))
    return rows


def region_summary(g, mask, curve, marks, bands, tas, places):
    """Area, sides, latitudes, heights, rain, runoff, warmth, water distance and light of a set of grid cells."""
    dry, land = g['dry'] * mask, g['land'] * mask
    total = float(dry.sum())
    if total <= 0.0:
        return None
    alat = np.abs(g['LA'])
    lat_q = weighted_pct(alat[mask], dry[mask], (0.1, 0.5, 0.9))
    hsl = g['hsl_km']
    mean_h = float((hsl * dry).sum() / total)
    up = dict(high=r(float(dry[(g['side'] == 0) & (g['earth_elev'] >= HIGH_EARTH_DEG)].sum()) / total),
              low=r(float(dry[(g['side'] == 0) & (g['earth_elev'] < HIGH_EARTH_DEG)].sum()) / total),
              rising_and_setting=r(float(dry[g['side'] == 1].sum()) / total),
              never=r(float(dry[g['side'] == 2].sum()) / total))
    out = dict(
        dry_land_km2=r(total, 4), share_of_moon_dry_land=r(total / g['dry'].sum()),
        abs_lat_deg_p10_p50_p90=rr(lat_q), height_above_sea_km_mean=r(mean_h),
        height_above_sea_km_p10_p90=rr(weighted_pct(hsl[mask], dry[mask], (0.1, 0.9))),
        rain_mm_day=r(float((g['pr'] * dry).sum() / total)),
        runoff_generated_km3_year=r(km3_year(g['runoff'], land), 4),
        bands_dry_land_km2={b: r(float((dry * m).sum()), 4) for b, m in bands.items()},
        km_to_standing_water_p50_p90=rr(weighted_pct(g['dist']['any_water'][mask], dry[mask], (0.5, 0.9))),
        km_to_sea_or_great_water_p50_p90=rr(weighted_pct(g['dist']['sea'][mask], dry[mask], (0.5, 0.9))),
        earth_up_shares=up)
    out['warmth'] = warmth(tas, g, mask, dry, mean_h)
    out['light'] = [twilight(p, marks, curve) for p in lat_q]
    far = mask & (g['side'] == 2)
    far_lat = weighted_pct(alat[far], g['dry'][far], (0.5,))[0] if g['dry'][far].sum() > 0 else None
    out['night_by_sky'] = night_by_sky(up, far_lat, places, marks, curve)
    tide = g['tide'][mask]
    if np.isfinite(tide).any():
        tw = dry[mask][np.isfinite(tide)]
        tv = tide[np.isfinite(tide)]
        out['sea_coast_monthly_tide_m'] = dict(share_of_land_on_sea_coasts=r(float(tw.sum()) / total),
                                               mean=r(float((tv * tw).sum() / tw.sum())),
                                               range=rr([float(tv.min()), float(tv.max())]))
    return out


