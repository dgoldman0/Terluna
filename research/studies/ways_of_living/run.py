def mean_cube_speed(winds, height_km):
    """Mean cube of the 3-day-mean speed at a height, from the stored quantiles (piecewise linear in quantile)."""
    hk = np.asarray(winds['height_km'], float)
    q = [0.0, 0.1, 0.5, 0.9, 0.99, 0.999, 1.0]
    v = [0.0] + [float(np.interp(height_km, hk, winds[k])) for k in
                 ('speed_p10_m_s', 'speed_p50_m_s', 'speed_p90_m_s', 'speed_p99_m_s', 'speed_p99_9_m_s',
                  'speed_max_m_s')]
    grid = np.linspace(0.0, 1.0, 20001)
    return float(np.trapezoid(np.interp(grid, q, v) ** 3, grid))


