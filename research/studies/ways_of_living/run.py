def food_fill(need_eq_km2, avail_km2_by_band, yield_by_band):
    """Crops placed wettest land first at each band's yield (crop-model equivalents per km2): the land they take
    in each band and what the bands cannot grow."""
    order = sorted(avail_km2_by_band, key=lambda b: -yield_by_band[b])
    remaining = need_eq_km2
    used = {}
    for b in order:
        y = yield_by_band[b]
        take = min(remaining, max(avail_km2_by_band[b], 0.0) * y)
        used[b] = take / y if y > 0 else 0.0
        remaining -= take
    return used, max(remaining, 0.0)


