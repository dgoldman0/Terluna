class MissingInput(RuntimeError):
    """An ignored grid product or a bound input on another branch is not available here."""


def sha256(path) -> str:
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def digest(path) -> str:
    return sha256(path)[:16]


def load_json(rel, schema):
    data = json.loads((ROOT / rel).read_text())
    if data.get('schema') != schema:
        raise ValueError(f'Unexpected schema in {rel}: {data.get("schema")}')
    return data


def load_npz(rel, schema):
    path = ROOT / rel
    if not path.exists():
        raise MissingInput(f'{rel} is not present; regenerate it in its domain')
    with np.load(path, allow_pickle=False) as z:
        data = {k: z[k] for k in z.files}
    meta = json.loads(str(data.pop('metadata')))
    if meta.get('schema') != schema:
        raise ValueError(f'Unexpected schema in {rel}: {meta.get("schema")}')
    return data, meta


def bound_bytes(key) -> bytes:
    """The bound input's bytes at its pinned commit, read through Git; the hash is checked."""
    b = BOUND[key]
    try:
        raw = subprocess.run(['git', 'show', f"{b['commit']}:{b['path']}"], cwd=ROOT, capture_output=True,
                             check=True).stdout
    except (OSError, subprocess.CalledProcessError) as error:
        raise MissingInput(f"{b['path']} at {b['branch']} {b['commit']} is not readable here") from error
    if hashlib.sha256(raw).hexdigest() != b['sha256']:
        raise ValueError(f"{b['path']} at {b['commit']} does not match its pinned hash")
    return raw


def load_bound(key):
    data = json.loads(bound_bytes(key))
    if data.get('schema') != BOUND[key]['schema']:
        raise ValueError(f'Unexpected schema in bound input {key}')
    return data


def r(x, n=3):
    """Round a float to n significant figures for the product."""
    if x is None or isinstance(x, (bool, int, str)):
        return x
    x = float(x)
    if x == 0.0 or not math.isfinite(x):
        return x
    return float(f'{x:.{n}g}')


def rr(seq, n=3):
    return [r(x, n) for x in seq]


