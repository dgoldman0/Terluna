# Light through the lunar day.

def lux_curve(calendar):
    table = calendar['sky']['ground_lux_by_sun_elevation']
    el, lux = np.asarray(table['elevation_deg'], float), np.asarray(table['lux'], float)
    order = np.argsort(el)
    return el[order], lux[order]


def elevation_at(lux, curve):
    el, lx = curve
    return float(np.interp(math.log(lux), np.log(lx), el))


def lux_at(elevation, curve):
    el, lx = curve
    return float(np.exp(np.interp(elevation, el, np.log(lx))))


def hours_to_depression(phi_deg, depression_deg):
    """Hours after sunset for the Sun to sink depression_deg below the horizon at latitude phi (zero declination);
    None where it never sinks that far."""
    c = math.cos(math.radians(phi_deg))
    if c <= 0.0:
        return None
    x = -math.sin(math.radians(depression_deg)) / c
    if x < -1.0:
        return None
    return (math.degrees(math.acos(x)) - 90.0) / 360.0 * SYNODIC_MONTH_DAYS * 24.0


def twilight(phi_deg, marks, curve):
    """The light calendar at a latitude from the solved clear sky: day, practical dusk, day vision, dark hours.
    An entry of None after sunset means that light lasts the whole night."""
    night = SYNODIC_MONTH_DAYS * 24.0 / 2.0
    out = dict(lat_deg=r(phi_deg), day_hours=r(night, 4), night_hours=r(night, 4))
    for key, elevation in marks.items():
        h = hours_to_depression(abs(phi_deg), -elevation)
        out[f'{key}_ends_after_sunset_hours'] = r(h) if h is not None else None
    dusk = hours_to_depression(abs(phi_deg), -marks['practical_dusk'])
    dim = hours_to_depression(abs(phi_deg), -marks['below_0_1_lux'])
    out['beyond_practical_dusk_hours'] = r(night - 2.0 * dusk) if dusk is not None else 0.0
    out['below_0_1_lux_sky_hours'] = r(night - 2.0 * dim) if dim is not None else 0.0
    out['darkest_sky_lux'] = r(lux_at(-(90.0 - abs(phi_deg)), curve))
    return out


def sun_up_longer_aloft_hours(height_km, phi_deg=0.0):
    """Extra hours of Sun at each end of the day for an eye height_km up (geometric horizon dip, no refraction)."""
    dip = math.degrees(math.acos(MOON_RADIUS / (MOON_RADIUS + height_km * 1e3)))
    rate = 360.0 / (SYNODIC_MONTH_DAYS * 24.0) * math.cos(math.radians(phi_deg))
    return dip / rate


