def food_account(lunar, crop_m2, rain_fed, water_need, kept, tw_per_km3_year, river_km3, diets, eco):
    """Food for the lunar residents against the rain-fed land outside the kept share (ecology's totals)."""
    need = [lunar * 1e9 * x / KM2 for x in crop_m2]
    out = {}
    for k in kept:
        cap = [x * (1.0 - k) for x in rain_fed]
        excess = [max(0.0, need[0] - cap[1]), max(0.0, need[1] - cap[0])]
        irrigation = [excess[0] * water_need[0] * 1e-6 * JULIAN_YEAR_DAYS,
                      excess[1] * water_need[1] * 1e-6 * JULIAN_YEAR_DAYS]
        out[f'kept_{int(k * 100)}'] = dict(
            cropland_equivalent_km2=rr(need, 4),
            share_of_rain_fed_land_outside_kept=rr([need[0] / cap[1], need[1] / cap[0]]),
            beyond_rain_km2=rr(excess, 4), irrigation_km3_year=rr(irrigation, 4),
            irrigation_share_of_river_flow=rr([w / river_km3 for w in irrigation]),
            irrigation_lift_from_seas_tw=rr([w * tw_per_km3_year for w in irrigation]),
            grazing_share_of_fog_desert=rr([lunar * 1e9 * x / KM2 / eco['capacity']['fog_desert_km2']
                                            for x in diets['plant_rich']['grazing_m2']]))
    return out


def place_surface(mix, surface_billion, homes, fixed):
    """People (billions) in each surface setting under a mix: the fixed settings first, the rest by weighted land."""
    people = dict(fixed)
    rest = surface_billion - sum(fixed.values())
    if rest < 0:
        raise ValueError('Fixed settings exceed the surface population')
    weights = {k: (MIX_WEIGHT if k in MIXES[mix]['favoured'] else 1.0) * homes[k] for k in SURFACE_MIXED}
    total = sum(weights.values())
    for k, w in weights.items():
        people[k] = rest * w / total
    return people


