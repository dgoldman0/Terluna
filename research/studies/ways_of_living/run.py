def surface_account(people, fp, homes, home_band_share, home_eco_share, kept, band_runoff, gross, makeup, dry_total,
                    lunar, crop_m2, eco_band_dry, support, wet_bands, water_need, tw_per_km3_year):
    """A surface mix: footprints against the homes, towns and rain-fed crops together on the land by band, and
    domestic water against each band's runoff."""
    out = dict(people_billion={k: r(v, 6) for k, v in people.items()})
    foot, share = {}, {}
    for k, v in people.items():
        key = next(s['footprint'] for s in SETTINGS if s['id'] == k)
        if key not in fp:
            continue
        foot[k] = [v * 1e9 * x / KM2 for x in fp[key]]
        if k in homes and k != 'summit_metropolis':
            share[k] = {f'kept_{int(kk * 100)}': rr([x / (homes[k] * (1.0 - kk)) for x in foot[k]]) for kk in kept}
    out['settlement_share_of_home_outside_kept'] = share
    total = [sum(v[0] for v in foot.values()), sum(v[1] for v in foot.values())]
    out['settlement_km2_total'] = rr(total, 4)
    out['settlement_share_of_dry_land'] = rr([total[0] / dry_total, total[1] / dry_total])
    # towns and crops on the land by ecology's bands: crops on the rain alone, wettest land first
    towns_band = {kb: [0.0, 0.0] for kb in eco_band_dry}
    for k, km2 in foot.items():
        if k in home_eco_share:
            for kb, sh in home_eco_share[k].items():
                towns_band[kb][0] += km2[0] * sh
                towns_band[kb][1] += km2[1] * sh
        elif k == 'summit_metropolis':
            towns_band['0-15'][0] += km2[0]
            towns_band['0-15'][1] += km2[1]
    need = [lunar * 1e9 * x / KM2 for x in crop_m2]
    land_use, rain_first, irrigated = {}, {}, {}
    belt = ('0-15', '15-30')
    wet = [kb for kb in eco_band_dry if wet_bands[kb]]
    for kk in kept:
        tag = f'kept_{int(kk * 100)}'
        avail = [{kb: eco_band_dry[kb] * (1 - kk) - towns_band[kb][i] for kb in eco_band_dry} for i in (0, 1)]
        # (a) on the rain alone where most land is wet, wettest first; what rain cannot grow is irrigated
        fills = [food_fill(need[i], {kb: avail[i][kb] for kb in wet}, {kb: support[kb][1 - i] for kb in wet})
                 for i in (0, 1)]
        left = [fills[i][1] for i in (0, 1)]
        water_a = [left[i] * water_need[i] * 1e-6 * JULIAN_YEAR_DAYS for i in (0, 1)]
        rain_first[tag] = dict(
            crops_km2_rain_belt=rr([sum(fills[i][0].get(kb, 0.0) for kb in belt) for i in (0, 1)], 4),
            crops_km2_beyond_30_deg=rr([sum(v for kb, v in fills[i][0].items() if kb not in belt)
                                        for i in (0, 1)], 4),
            beyond_rain_km2=rr(left, 4), irrigation_km3_year=rr(water_a, 4),
            irrigation_lift_from_seas_tw=rr([x * tw_per_km3_year for x in water_a]))
        land = sum(eco_band_dry[kb] * (1 - kk) for kb in belt)
        land_use[tag] = rr([sum(towns_band[kb][i] + fills[i][0].get(kb, 0.0) for kb in belt) / land
                            for i in (0, 1)])
        # (b) every crop irrigated to the crop model's yield in the rain belt, wettest first
        full = [food_fill(need[i], {kb: avail[i][kb] for kb in belt}, {kb: 1.0 for kb in belt}) for i in (0, 1)]
        water_b = [sum(full[i][0][kb] * water_need[i] * (1.0 - support[kb][1 - i]) for kb in belt) * 1e-6 *
                   JULIAN_YEAR_DAYS for i in (0, 1)]
        irrigated[tag] = dict(
            crops_km2=rr([sum(full[i][0].values()) for i in (0, 1)], 4),
            rain_belt_land_use=rr([sum(towns_band[kb][i] + full[i][0][kb] for kb in belt) / land for i in (0, 1)]),
            beyond_the_rain_belt_land_km2=rr([full[i][1] for i in (0, 1)], 4),
            irrigation_km3_year=rr(water_b, 4), irrigation_lift_from_seas_tw=rr([x * tw_per_km3_year for x in water_b]))
    out['food_rain_fed_first'] = rain_first
    out['food_all_irrigated'] = irrigated
    out['rain_belt_land_use'] = land_use
    band_people = {b: 0.0 for b in band_runoff}
    for k, v in people.items():
        if k in home_band_share:
            for b, sh in home_band_share[k].items():
                band_people[b] += v * sh
        elif k == 'undersea_communities':
            band_people['equatorial'] += v
    water = {}
    for b, p in band_people.items():
        g_km3 = [p * x for x in gross]
        m_km3 = [p * x for x in makeup]
        ro = band_runoff[b]
        water[b] = dict(people_billion=r(p, 4), makeup_km3_year=rr(m_km3),
                        gross_share_of_runoff=rr([x / ro for x in g_km3]) if ro > 0 else None,
                        makeup_share_of_runoff=rr([x / ro for x in m_km3]) if ro > 0 else None,
                        gross_lift_from_seas_gw=rr([x * tw_per_km3_year * 1e3 for x in g_km3]))
    out['domestic_water_by_band'] = water
    return out


def sky_account(total, a, settings, sky_area, rain_all, kept, moon_km2, drift_share=None):
    """The sky towns of a case and share: envelopes, mass, gas, the sky's share and their spacing by band, spread
    evenly over the sky clear of terrain and, where the winds' diagnostic exists, as drifting towns gather."""
    n = total * 1e9 / a['residents_per_envelope']
    pb = settings['roaming_sky_towns']['per_billion']
    out = dict(envelopes=r(n, 4),
               mass_gt=r(total * (pb['district_gt']['50.0'] + pb['carrier_and_services_gt'])),
               reserve_gt=r(total * pb['unallocated_reserve_gt']),
               lifting_gas_mixture_gt=r(total * pb['lifting_gas_mixture_gt']),
               hydrogen_gt=r(total * pb['hydrogen_gt']),
               projected_share_of_moon=r(n * a['projected_km2_per_envelope'] / moon_km2))
    hu = a['hydrogen_upkeep']
    per = hu['per_billion_per_percent_a_year']
    pct = [100.0 * x for x in hu['loss_bracket_per_year']]
    out['hydrogen_upkeep'] = dict(
        loss_per_year=hu['loss_bracket_per_year'],
        released_mt_year=rr([total * per['released_mt_year'] * p for p in pct]),
        remake_tw=rr([total * per['remake_tw'][0] * pct[0], total * per['remake_tw'][1] * pct[1]]),
        air_hydrogen_ppm_held=rr([total * per['air_hydrogen_ppm_held'] * p for p in pct]))
    clear = sum(sky_area.values())
    belt = sky_area['equatorial'] + sky_area['tropical']
    storm_km2 = math.pi * (a['storm_width_km'] / 2.0) ** 2
    diag = SPACING_DIAMETERS * 2.0 * a['envelope_radius_m'] / 1e3
    boat_speed = a['sky_boat']['cruise_m_s']
    by_band = {}
    for b, area in sky_area.items():
        towns = n * area / clear
        row = dict(towns=r(towns, 4),
                   rain_catch_l_per_resident_day=r(rain_all[b] * pb['rain_catchment_l_per_resident_per_mm_day']))
        for k in kept:
            sp = math.sqrt(area * (1.0 - k) / towns) if towns > 0 else None
            row[f'spacing_km_kept_{int(k * 100)}'] = r(sp)
            row[f'towns_per_storm_kept_{int(k * 100)}'] = r(storm_km2 / sp ** 2) if sp else None
            row[f'minutes_to_neighbour_by_sky_boat_kept_{int(k * 100)}'] = r(sp * 1e3 / boat_speed / 60.0) if sp else None
        if drift_share is not None:
            towns_d = n * drift_share[b]
            row['drifting_towns'] = r(towns_d, 4)
            for k in kept:
                sp = math.sqrt(area * (1.0 - k) / towns_d) if towns_d > 0 else None
                row[f'drifting_spacing_km_kept_{int(k * 100)}'] = r(sp)
                row[f'drifting_towns_per_storm_kept_{int(k * 100)}'] = r(storm_km2 / sp ** 2) if sp else None
        by_band[b] = row
    out['by_band'] = by_band
    out['rain_belt_only'] = {}
    out['spacing_over_grid_diagnostic_whole_sky'] = {}
    for k in kept:
        tag = f'kept_{int(k * 100)}'
        sp = math.sqrt(belt * (1.0 - k) / n) if n > 0 else None
        out['rain_belt_only'][tag] = dict(spacing_km=r(sp), towns_per_storm=r(storm_km2 / sp ** 2) if sp else None,
                                          spacing_over_grid_diagnostic=r(sp / diag) if sp else None)
        out['spacing_over_grid_diagnostic_whole_sky'][tag] = r(math.sqrt(clear * (1 - k) / n) / diag) if n > 0 else None
    return out


def aerial_account(amix, people, a, settings, sky_trip_kw):
    """An aerial mix: who lives in which kind of sky town, and the power they take to operate."""
    total = sum(people.values())
    out = dict(people_billion={k: r(v, 6) for k, v in people.items()})
    duty = a['roaming_kw_per_resident']
    roam = people.get('roaming_sky_towns', 0.0)
    held = people.get('moored_or_streamlined_sky_towns', 0.0)
    control = [roam * duty[k] for k in sorted(duty, key=float)]
    hold = 0.0
    if held > 0.0 and amix == 'streamlined':
        hold = held * a['hull_hold_place_kw_per_resident']
        out['holding_tw'] = r(hold)
        out['follow_sun_tw_by_lat'] = {k: r(held * v) for k, v in a['hull_follow_sun_kw_per_resident_by_lat'].items()}
    elif held > 0.0:
        out['tether_gt'] = r(held * settings['moored_or_streamlined_sky_towns']['per_billion']['moored_tether_gt'])
    trips = total * sky_trip_kw
    out['control_tw_by_duty'] = rr(control)
    out['trips_down_tw'] = r(trips)
    out['operating_tw'] = rr([control[0] + hold + trips, control[1] + hold + trips, control[2] + hold + trips])
    return out


