def per_billion(s, ctx):
    """What a billion residents of one setting take beyond the costs every lunar resident shares."""
    b = 1e9
    out = {}
    kind = s['kind']
    fp = ctx['fp']
    if s['footprint'] in fp:
        m2 = fp[s['footprint']]
        out['settlement_km2'] = rr([b * x / KM2 for x in m2], 4)
        home = ctx['homes'].get(s['id'])
        if home and s['id'] != 'summit_metropolis':
            for kept in ctx['kept']:
                out[f'settlement_share_of_home_outside_kept_{int(kept * 100)}'] = rr(
                    [b * x / KM2 / (home * (1.0 - kept)) for x in m2])
                out[f'home_built_over_outside_kept_{int(kept * 100)}_holds_billion'] = rr(
                    [home * (1.0 - kept) * KM2 / x / b for x in m2[::-1]])
        out['heat_over_town_w_m2'] = {k: rr([e * 1e3 / x for x in m2]) for k, e in ctx['released'].items()}
        out['people_per_km2_of_town'] = rr([KM2 / x for x in m2])
        out['busy_hour_flyers_per_km2'] = r(ctx['flyers_pp'] * KM2 / m2[0])
        out['sky_boat_trip_share_nasa_lanes_hold'] = r(min(1.0, ctx['nasa_share'] * ctx['metro_density'] /
                                                           (KM2 / m2[0])))
    if s['home']:
        runoff = ctx['regions'][CLASSES[s['home'][0]]]['runoff_generated_km3_year']
        out['home_runoff_km3_year'] = runoff
        out['domestic_gross_share_of_home_runoff'] = rr([x / runoff for x in ctx['gross_pb']]) if runoff else None
        out['domestic_makeup_share_of_home_runoff'] = rr([x / runoff for x in ctx['makeup_pb']]) if runoff else None
        out['domestic_gross_lift_from_seas_gw'] = rr([x * ctx['tw_per_km3_year'] * 1e3 for x in ctx['gross_pb']])
    if kind == 'lunar_aerial' and s['id'] != 'high_platforms':
        a = ctx['aerial']
        n = b / a['residents_per_envelope']
        shares = a['lift_shares']
        gross_kg = b * a['gross_lift_t_per_resident'] * 1e3
        out.update(envelopes=r(n, 4),
                   district_gt={k: r(b * v * 1e3 / GT) for k, v in a['districts_t_per_person'].items()},
                   carrier_and_services_gt=r(gross_kg * (shares['envelope_flight_structure'] +
                                                         shares['control_flight_services']) / GT),
                   unallocated_reserve_gt=r(gross_kg * shares['reserve'] / GT),
                   lifting_gas_mixture_gt=r(b * a['gas_mixture_t_per_resident'] * 1e3 / GT),
                   hydrogen_gt=r(b * a['lifting_species_t_per_resident'] * 1e3 / GT),
                   projected_km2=r(n * a['projected_km2_per_envelope'], 4),
                   projected_share_of_moon=r(n * a['projected_km2_per_envelope'] / ctx['moon_km2']),
                   rain_catchment_l_per_resident_per_mm_day=r(a['projected_km2_per_envelope'] * KM2 /
                                                              a['residents_per_envelope']),
                   trips_down_tw=r(ctx['sky_trip_kw']),
                   hydrogen_upkeep_per_percent_a_year=a['hydrogen_upkeep']['per_billion_per_percent_a_year'])
        if s['id'] == 'roaming_sky_towns':
            out['control_tw_by_duty'] = {k: r(v) for k, v in a['roaming_kw_per_resident'].items()}
        else:
            out['moored_holding_tw'] = 0.0
            out['moored_tether_gt'] = r(n * a['tether']['steel_t_per_envelope'] * 1e3 / GT)
            out['streamlined_hold_place_tw'] = r(a['hull_hold_place_kw_per_resident'])
            out['streamlined_follow_sun_tw_by_lat'] = a['hull_follow_sun_kw_per_resident_by_lat']
    if kind == 'orbital':
        arr = ctx['pop']['array']
        hab = arr['habitats']['1_billion']
        out.update(shield_gt=rr(hab['shield_gt']), times_fleet_mass=r(hab['times_fleet_mass']),
                   days_of_matter_stream=r(hab['days_of_matter_stream']),
                   years_of_film_plant_output=rr(hab['years_of_film_plant_output']), farm_km2=r(hab['farm_km2']),
                   power_tw=r(hab['power_tw']),
                   commute_kw_per_commuter={k: rr(v) for k, v in
                                            ctx['pop']['commute']['transfers']['hohmann']['continuous_kw_per_commuter']
                                            .items()},
                   energy_tw={k: r(v) for k, v in ctx['band'].items()},
                   heat_on_moon_w_m2_per_tw_released=r(arr['moon_w_m2_per_tw_in_orbit']))
    if kind == 'earth':
        food = ctx['pop']['food']
        farmland_ha = food['earth_farmland_ha_per_person_now'] * ctx['pop']['horizons']['today_billion'] * 1e9
        out.update(plant_rich_farmland_km2=rr([b * x * 1e4 / KM2 for x in food['plant_rich_ha_per_person']], 4),
                   share_of_todays_farmland=rr([b * x / farmland_ha for x in food['plant_rich_ha_per_person']]),
                   energy_tw={k: r(v) for k, v in ctx['band'].items()},
                   warming_k_thermal_plants={k: r(v['k_per_billion_thermal'])
                                             for k, v in ctx['pop']['heat']['earth'].items()})
    if kind == 'elsewhere':
        out['energy_tw'] = {k: r(v) for k, v in ctx['band'].items()}
    return out


